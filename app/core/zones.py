def find_zone_for_tid(tid) -> tuple[int, int]:
    """根据 tid 返回 (一级索引, 二级索引)。

    先匹配二级 tid；匹配不到时尝试匹配一级 tid（旧配置存了一级 tid），
    映射到该一级分区的第一个二级分区。都匹配不到返回 (1, 0)（生活·日常）。
    """
    try:
        tid = int(tid)
    except (TypeError, ValueError):
        tid = 0
    for zi, (_name, _zone_tid, subs) in enumerate(ZONE_TREE):
        for si, (_sub_name, sub_tid) in enumerate(subs):
            if sub_tid == tid:
                return zi, si
    for zi, (_name, zone_tid, subs) in enumerate(ZONE_TREE):
        if zone_tid == tid and subs:
            return zi, 0
    return 1, 0
